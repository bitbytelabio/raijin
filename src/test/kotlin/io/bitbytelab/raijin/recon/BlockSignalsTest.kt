package io.bitbytelab.raijin.recon

import io.bitbytelab.raijin.core.ProbeResult
import kotlin.test.Test
import kotlin.test.assertEquals
import kotlin.test.assertNull

class BlockSignalsTest {

    private fun response(status: Int, body: String = "", vararg headers: Pair<String, String>) = ProbeResult(status, body, mapOf(*headers))

    @Test
    fun `a 429 backs off longer with every retry`() {
        assertEquals(1000L, BlockSignals.throttleDelayMs(response(429), 0))
        assertEquals(3000L, BlockSignals.throttleDelayMs(response(429), 1))
        assertEquals(6000L, BlockSignals.throttleDelayMs(response(429), 2))
        assertEquals(6000L, BlockSignals.throttleDelayMs(response(429), 9))
    }

    @Test
    fun `Retry-After is honoured within bounds`() {
        assertEquals(2000L, BlockSignals.throttleDelayMs(response(429, "", "retry-after" to "2"), 0))
        assertEquals(10_000L, BlockSignals.throttleDelayMs(response(429, "", "retry-after" to "3600"), 0))
        assertEquals(500L, BlockSignals.throttleDelayMs(response(429, "", "retry-after" to "0"), 0))
        // A date instead of seconds: fall back to the schedule.
        assertEquals(3000L, BlockSignals.throttleDelayMs(response(429, "", "retry-after" to "Wed, 21 Oct 2026 07:28:00 GMT"), 1))
    }

    @Test
    fun `a 503 is a rate limit only when it says when to come back`() {
        assertEquals(5000L, BlockSignals.throttleDelayMs(response(503, "", "retry-after" to "5"), 0))
        assertNull(BlockSignals.throttleDelayMs(response(503, "Service Unavailable"), 0))
        assertNull(BlockSignals.throttleDelayMs(response(200, "ok", "retry-after" to "5"), 0))
        assertNull(BlockSignals.throttleDelayMs(response(403, "Forbidden"), 0))
    }

    @Test
    fun `block and challenge pages are recognised by vendor`() {
        assertEquals("cloudflare", BlockSignals.blockedBy(response(403, "<title>Attention Required! | Cloudflare</title>")))
        assertEquals("cloudflare", BlockSignals.blockedBy(response(503, "<title>Just a moment...</title> ... Cloudflare Ray ID")))
        assertEquals("cloudflare", BlockSignals.blockedBy(response(200, "<html>challenge</html>", "cf-mitigated" to "challenge")))
        assertEquals("akamai", BlockSignals.blockedBy(response(403, "<H1>Access Denied</H1> You don't have permission. Reference&#32;&#35;18.2d351ab8")))
        assertEquals("imperva", BlockSignals.blockedBy(response(403, "Request unsuccessful. Incapsula incident ID: 123-456")))
        assertEquals("aws-waf", BlockSignals.blockedBy(response(403, "<h1>403 ERROR</h1> Request blocked. Generated by cloudfront (CloudFront)")))
        assertEquals("aws-waf", BlockSignals.blockedBy(response(202, "", "x-amzn-waf-action" to "challenge")))
        assertEquals("f5-asm", BlockSignals.blockedBy(response(403, "The requested URL was rejected. Please consult with your administrator. Your support ID is: 123")))
        assertEquals("modsecurity", BlockSignals.blockedBy(response(406, "Not Acceptable! This error was generated by Mod_Security.")))
        assertEquals("sucuri", BlockSignals.blockedBy(response(403, "Access Denied - Sucuri Website Firewall")))
        assertEquals("captcha", BlockSignals.blockedBy(response(429, "<div class=\"g-recaptcha\" data-sitekey=\"x\"></div>")))
    }

    @Test
    fun `an application's own refusal is not a block page`() {
        assertNull(BlockSignals.blockedBy(response(403, "Forbidden")))
        assertNull(BlockSignals.blockedBy(response(404, "Not Found")))
        assertNull(BlockSignals.blockedBy(response(401, "{\"error\":\"unauthorized\"}")))
        // Vendor words on a page that was served normally say nothing.
        assertNull(BlockSignals.blockedBy(response(200, "We protect this site with Cloudflare. Sorry, you have been blocked is what attackers see.")))
        assertNull(BlockSignals.blockedBy(response(200, "<div class=\"g-recaptcha\"></div>", "cf-ray" to "8a1b2c3d4e5f-LHR")))
    }
}
