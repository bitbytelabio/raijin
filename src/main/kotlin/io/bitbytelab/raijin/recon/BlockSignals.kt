package io.bitbytelab.raijin.recon

import io.bitbytelab.raijin.core.ProbeResult
import kotlin.math.min

/** Tells a rate limit or a WAF / bot-protection page from the application's own answer. */
object BlockSignals {
    private val BACKOFF_MS = longArrayOf(1_000, 3_000, 6_000)
    private const val MIN_BACKOFF_MS = 500L
    private const val MAX_BACKOFF_MS = 10_000L

    /** Block pages are short; the vendor markers sit near the top. */
    private const val BODY_SCAN_CHARS = 20_000
    private val BLOCK_STATUSES = setOf(403, 406, 429, 503)

    /**
     * How long to wait before asking again when [response] is a rate limit (429, or 503 with
     * Retry-After); null when it is not one. [attempt] counts the retries already made.
     */
    fun throttleDelayMs(response: ProbeResult, attempt: Int): Long? {
        val retryAfter = response.header("retry-after")?.trim()
        if (response.status != 429 && !(response.status == 503 && retryAfter != null)) return null
        val seconds = retryAfter?.toLongOrNull()
            ?: return BACKOFF_MS[min(attempt.coerceAtLeast(0), BACKOFF_MS.size - 1)]
        return (seconds * 1000L).coerceIn(MIN_BACKOFF_MS, MAX_BACKOFF_MS)
    }

    /**
     * The WAF or bot protection whose block or challenge page [response] is, or null when the
     * response does not look like one. Only responses with a blocking status are examined, apart
     * from a challenge the edge announces in a header.
     */
    fun blockedBy(response: ProbeResult): String? {
        if (response.header("cf-mitigated")?.contains("challenge", ignoreCase = true) == true) return "cloudflare"
        if (response.header("x-amzn-waf-action") != null) return "aws-waf"
        if (response.status !in BLOCK_STATUSES) return null
        val body = response.body.take(BODY_SCAN_CHARS).lowercase()
        return when {
            "attention required! | cloudflare" in body || "cf-error-details" in body ||
                ("cloudflare" in body && ("sorry, you have been blocked" in body || "just a moment..." in body)) ||
                "/cdn-cgi/challenge-platform/" in body -> "cloudflare"
            "access denied" in body && ("errors.edgesuite.net" in body || "reference&#32;&#35;" in body || "reference #" in body) -> "akamai"
            "incapsula incident id" in body || "_incapsula_resource" in body -> "imperva"
            "request blocked" in body && "cloudfront" in body -> "aws-waf"
            "sucuri website firewall" in body -> "sucuri"
            "the requested url was rejected" in body && "support id" in body -> "f5-asm"
            "mod_security" in body || "modsecurity" in body -> "modsecurity"
            "generated by wordfence" in body -> "wordfence"
            "captcha-delivery.com" in body || response.header("x-datadome") != null -> "datadome"
            "px-captcha" in body || "access to this page has been denied" in body -> "perimeterx"
            "web page blocked" in body && "attack id" in body -> "fortiweb"
            "unauthorized activity has been detected" in body -> "radware"
            "ddos-guard" in body -> "ddos-guard"
            "g-recaptcha" in body || "h-captcha" in body || "cf-turnstile" in body -> "captcha"
            else -> null
        }
    }
}
